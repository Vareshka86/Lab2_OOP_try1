#ifndef BOOK_H
#define BOOK_H

#include "Author.h"

#include <string>

/**
 * @brief Книга из библиотеки — один экземпляр, который выдают читателям.
 * @details Книга знает своё название, автора и год издания, а также своё
 * текущее положение: стоит на полке, выдана читателю или списана.
 *
 * Инварианты (условия корректности объекта):
 * 1. Название не пустое.
 * 2. Год издания — от MIN_YEAR до текущего года и позже года рождения
 *    автора, если тот известен.
 * 3. Выданная книга записана на читателя (имя не пустое); книга на полке
 *    ни на кого не записана.
 * 4. Списанная книга не выдана и выдать её нельзя.
 * 5. Число выдач не отрицательное и увеличивается только при выдаче.
 *
 * Конструкторы проверяют инварианты 1–2 и при нарушении бросают исключение,
 * поэтому некорректный объект не может появиться. Методы изменения проверяют
 * инварианты 3–5: недопустимую операцию они отклоняют — возвращают false,
 * сообщают причину и оставляют книгу без изменений.
 *
 * Статический счётчик count_ хранит число существующих книг: его увеличивают
 * все конструкторы (включая конструктор копирования), а уменьшает деструктор.
 */
class Book
{
public:
    /// Наименьший допустимый год издания: книгопечатание появилось около 1450 года.
    static const int MIN_YEAR = 1450;

    /**
     * @brief Конструктор по умолчанию: пустая библиотечная карточка.
     * @details Создаёт корректную книгу: название «Без названия», автор не указан,
     * год издания — текущий; книга на полке, выдач не было.
     */
    Book();

    /**
     * @brief Параметризованный конструктор: книга с названием, автором и годом издания.
     * @param title  Название книги.
     * @param author Автор книги — объект класса Author.
     * @param year   Год издания.
     * @exception std::invalid_argument Если название пустое или год издания нарушает
     *            инвариант 2. Объект в этом случае не создаётся.
     */
    Book(const std::string& title, const Author& author, int year);

    /**
     * @brief Конструктор копирования: новая книга — точная копия другой.
     * @details Копирует все поля и увеличивает счётчик книг: копия — это ещё
     * один существующий объект. Без явного конструктора копирования компилятор
     * создал бы свой, который счётчик не увеличивает, и после уничтожения
     * копий счётчик ушёл бы в минус.
     * @param other Книга, с которой снимается копия.
     */
    Book(const Book& other);

    /**
     * @brief Оператор присваивания: стандартное копирование всех полей.
     * @details Присваивание `a = b` не создаёт новой книги — объект `a` уже
     * существует и только получает значения полей `b`. Поэтому счётчик не
     * меняется, и подходит присваивание, которое делает компилятор
     * (`= default`). Оно объявлено явно, потому что у класса есть свои
     * конструктор копирования и деструктор (правило трёх).
     * @param other Книга, значения которой присваиваются.
     * @return Ссылка на этот объект (позволяет писать `a = b = c`).
     */
    Book& operator=(const Book& other) = default;

    /**
     * @brief Деструктор: сообщает, что время жизни книги закончилось.
     * @details Вызывается автоматически: для локального объекта — при выходе из
     * блока `{ }`, где он объявлен; для объекта, созданного через `new`, — при
     * `delete`. Уменьшает счётчик книг и выводит сообщение. Динамической памяти
     * класс не выделяет, поэтому освобождать нечего.
     */
    ~Book();

    /**
     * @brief Возвращает число существующих сейчас книг.
     * @details Статический метод: вызывается через имя класса — `Book::getCount()`,
     * объект для этого не нужен.
     * @return Сколько объектов Book создано и ещё не уничтожено.
     */
    static int getCount();

    /**
     * @brief Возвращает название книги.
     * @return Константная ссылка на название.
     */
    const std::string& getTitle() const;

    /**
     * @brief Возвращает автора книги.
     * @return Константная ссылка на объект Author.
     */
    const Author& getAuthor() const;

    /**
     * @brief Возвращает год издания.
     * @return Год издания.
     */
    int getYear() const;

    /**
     * @brief Проверяет, выдана ли книга читателю.
     * @return true — книга у читателя, false — нет.
     */
    bool isIssued() const;

    /**
     * @brief Возвращает имя читателя, у которого книга.
     * @return Имя читателя или пустая строка, если книга не выдана.
     */
    const std::string& getReaderName() const;

    /**
     * @brief Возвращает, сколько раз книгу выдавали.
     * @return Число выдач (не меньше 0).
     */
    int getIssueCount() const;

    /**
     * @brief Проверяет, списана ли книга.
     * @return true — книга списана, false — нет.
     */
    bool isWrittenOff() const;

    /**
     * @brief Выводит карточку книги в консоль.
     * @details Название, автор, год издания, положение книги и число выдач.
     * Метод константный: он только читает поля.
     */
    void print() const;

    /**
     * @brief Выдаёт книгу читателю.
     * @details Выдача разрешена, только если книга не списана, стоит на полке и имя
     * читателя не пустое (инварианты 3 и 4). При выдаче записывается читатель и
     * увеличивается число выдач (инвариант 5).
     * @param reader Имя читателя.
     * @return true — книга выдана; false — операция отклонена, книга не изменилась.
     */
    bool issueTo(const std::string& reader);

    /**
     * @brief Принимает книгу обратно от читателя.
     * @details Разрешено, только если книга выдана. Книга возвращается на полку,
     * имя читателя стирается (инвариант 3). Число выдач не меняется.
     * @return true — книга возвращена; false — книга не была выдана, ничего не изменилось.
     */
    bool returnBook();

    /**
     * @brief Списывает книгу из фонда библиотеки.
     * @details Списать можно только книгу на полке: выданную сначала нужно вернуть
     * (инвариант 4). Повторно списать уже списанную книгу нельзя. Списанную книгу
     * больше не выдают.
     * @return true — книга списана; false — операция отклонена, книга не изменилась.
     */
    bool writeOff();

private:
    static int count_;       ///< Число существующих объектов Book (общее для всех книг)

    std::string title_;      ///< Название (не пустое)
    Author author_;          ///< Автор — объект пользовательского класса
    int year_;               ///< Год издания
    bool isIssued_;          ///< true — книга выдана читателю
    std::string readerName_; ///< Имя читателя, у которого книга (пусто, если не выдана)
    int issueCount_;         ///< Сколько раз книгу выдавали
    bool isWrittenOff_;      ///< true — книга списана и больше не выдаётся
};

#endif // BOOK_H
